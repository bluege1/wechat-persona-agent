def looks_like_confess(text: str) -> bool:
    """他这句是不是在表白。够强的一条就算 —— 这种事宁可直接判、别模糊。"""
    t = (text or "").strip()
    if not t or len(t) > 600:
        return False
    if any(k in t for k in CONFESS_STRONG):
        return True
    # 弱词要配一句「我是认真在说」的语气才算
    if any(k in t for k in CONFESS_WEAK) and re.search(
            r"认真|真心|我是说真的|不是开玩笑|想好了|想了很久", t):
        return True
    return False


def _short(t: str) -> bool:
    return len(_flat(t)) <= 6


_PUNCT_RE = re.compile(r"[\s。，、！!~～.,？?…—·\-]")
# 去标点/空白，短答比对就靠它
def _flat(t: str) -> str:
    return _PUNCT_RE.sub("", t or "")


def read_answer(text: str):
    """她表白之后，他这句是答应 / 拒绝 / 没答。

    返回 True（答应）/ False（拒绝）/ None（看不出来 —— 她会再问一遍）。

    ★ 短答**整句比对**，不做「包含就算」：
      早先写成「含『不』即拒绝」，把「今天天气不错」判成了拒绝 ——
      她当场掉档自暴自弃。宁可判成「没答」（她再问一遍），也不能误判成拒绝。
    """
    t = (text or "").strip()
    if not t:
        return None
    s = _flat(t)
    # ★★ 「还没答」的信号必须排在拒绝**之前**（2026-09-27 实测惨案）。
    #   当时他回的那句里带着「不想」（本意是犹豫 / 还没准备好），
    #   而 REFUSE_STRONG 是「包含就算」的匹配 —— 于是当场判成拒绝，
    #   refuse_her() 把亲密度从 2327 砍到 600、掉回第 3 档、进入 7 天自暴自弃期。
    #   这条路是**单向的**：她不会自己回来，只能人工撤销（见 _scan\撤销误判-升恋人.py）。
    #   他明明在说「让我再想想」，凭什么算拒绝？所以犹豫先判、拒绝后判。
    if any(k in s for k in _HEDGE):
        return None
    # ★ 拒绝词收得太宽，所以「包含就算」必须加条件。
    #   REFUSE_STRONG 里躺着「不想 / 不了 / 不行」这种满地都是的词 ——
    #   实测「这辈子都不想跟你分开」被判成拒绝（那是情话，不是拒绝）。
    #   真拒绝都说得**短而直接**，所以只在下面两种情况下才算拒绝：
    #     · 整句很短（≤8 字）——「算了」「我不想」「还是做朋友吧」；
    #     · 拒绝词就顶在句首 ——「不行 但我喜欢你」这种也算拒绝（他先否了）。
    #   长句里夹带一个（「我这辈子都不想跟你分开」）走不到这儿，落到「没答」，
    #   她会再问一遍 —— 让她多问一句，比让她当场掉档自暴自弃便宜太多。
    _hit = [k for k in REFUSE_STRONG if k in t]
    if _hit and (len(s) <= 8 or s.startswith(tuple(_hit))):
        return False
    if any(k in t for k in ACCEPT_STRONG):
        return True
    if len(s) <= 6:
        for k in REFUSE_SHORT:
            # 单字只认「整句就是它」—— 「不」不能靠「包含」去匹配
            # （不然「今天天气不错」「不知道啊」全成了拒绝）
            if len(k) == 1:
                if s == k:
                    return False
            elif s == k or s.startswith(k):
                return False
        for k in ACCEPT_SHORT:
            if len(k) == 1:
                if s == k:
                    return True
            elif s == k or s.startswith(k):
                return True
    return None


