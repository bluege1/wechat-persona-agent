def _now_hour(now=None) -> int:
    if isinstance(now, dt.datetime):
        return now.hour
    return dt.datetime.now().hour


def is_deep_night(now=None) -> bool:
    """她最不设防的那一段：22:30 – 02:00。"""
    if isinstance(now, dt.datetime):
        h, m = now.hour, now.minute
    else:
        n = now or dt.datetime.now()
        h, m = n.hour, n.minute
    return (h == 22 and m >= 30) or h == 23 or h == 0 or h == 1 or (h == 2 and m == 0)


def prep_score(text: str, *, weights=None, has_photo=False, has_voice=False,
               has_gift=False, build_count=0, past_words=None,
               now=None) -> dict:
    """算用心分。返回 {"score", "items":[...], "miss":[...], "night"}。

    text        : 他这条消息
    build_count : 最近 3 天里「聊到你们俩」的轮数
    past_words  : 额外的「你们之间的事」关键词（bridge 从 约定.json 递进来）
    """
    t = (text or "").strip()
    flat = re.sub(r"\s+", "", t)
    w = dict(weights or {})
    def wt(k, d):
        try:
            return max(0, int(w.get(k, d)))
        except Exception:
            return d

    night = is_deep_night(now)
    past_kw = list(CORE_PAST_WORDS) + [str(x) for x in (past_words or []) if x]

    det = {
        "len":   len(flat) >= 60,
        "name":  ("达妮娅" in t) or ("尼娅" in t),
        "past":  any(k and k in t for k in past_kw),
        "why":   bool(re.search(r"因为[^。！？!?]{20,}", t)) or
                 any(k in t for k in WHY_WORDS),
        "night": night,
        "build": int(build_count or 0) >= 3,
        "gift":  bool(has_photo or has_voice or has_gift),
    }

    items, miss, score = [], [], 0
    for key, label, how, dflt in PREP_ITEMS:
        weight = wt(key, dflt)
        got = bool(det.get(key))
        if got:
            score += weight
        else:
            miss.append({"key": key, "label": label, "how": how, "weight": weight})
        items.append({"key": key, "label": label, "how": how,
                      "weight": weight, "got": got})
    score = min(PREP_MAX, score)
    return {"score": score, "items": items, "miss": miss, "night": night,
            "max": PREP_MAX, "chars": len(flat),
            "ready": score >= 60}


def prep_tips(res: dict, limit: int = 3) -> str:
    """把「差在哪儿」拼成一句话 —— 她说不出口的那些提示，控制台上用。"""
    miss = list((res or {}).get("miss") or [])
    if not miss:
        return "挑不出毛病。"
    miss.sort(key=lambda m: -int(m.get("weight") or 0))
    return "、".join(m["label"] for m in miss[:limit])


